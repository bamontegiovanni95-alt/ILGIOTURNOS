create table if not exists public.appointments (
 id bigint generated by default as identity primary key,
 location text not null check (location in ('boedo','matheu')),
 barber text not null,
 start_at timestamptz not null,
 service text not null check (service in ('Corte','Corte y barba','Barba')),
 price integer not null,
 duration_minutes integer not null default 30 check (duration_minutes=30),
 customer_name text not null,
 customer_phone text not null,
 status text not null default 'confirmed' check (status in ('confirmed','cancelled')),
 created_at timestamptz not null default now(),
 constraint appointments_barber_start_unique unique(location,barber,start_at)
);
create index if not exists appointments_day_idx on public.appointments(location,barber,start_at);
alter table public.appointments enable row level security;
